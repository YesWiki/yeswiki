// Regenerates src/assets/icons.svg — the curated Tabler symbol sprite YesWiki's UI uses
// instead of an icon font. The set of icons is the value side of src/icon-map.json
// (historic FontAwesome name -> Tabler outline name); add an entry there, run
// `node src/build-icon-sprite.mjs`, commit both files.
//
// The sprite is committed on purpose: it is a curated asset the pages reference
// directly (<svg class="yw-icon"><use href="src/assets/icons.svg#name"/></svg>),
// not a build artifact users must regenerate.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const srcDir = dirname(fileURLToPath(import.meta.url))
const map = JSON.parse(readFileSync(join(srcDir, 'icon-map.json'), 'utf8'))
// icons needed beyond the legacy map (filled variants render as `${name}-filled`)
const EXTRAS = ['filled:star', 'cursor-text']
// sprite ids whose Tabler source icon has a different name — e.g. the magnifier
// ships as "loupe" because adblock cosmetic filters hide elements whose
// attributes mention "#search"
const RENAMES = { loupe: 'search' }

const names = [
  ...new Set([
    ...Object.entries(map)
      .filter(([key]) => key !== '__comment')
      .map(([, tablerName]) => tablerName),
    ...EXTRAS
  ])
].sort()

const symbols = names.map((ref) => {
  const [style, base] = ref.includes(':') ? ref.split(':') : ['outline', ref]
  const id = style === 'filled' ? `${base}-filled` : base
  const file = join(
    srcDir,
    '..',
    'node_modules',
    '@tabler',
    'icons',
    'icons',
    style,
    `${RENAMES[base] ?? base}.svg`
  )
  const svg = readFileSync(file, 'utf8')
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim()
  const paint = style === 'filled'
    ? 'fill="currentColor" stroke="none"'
    : 'fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"'
  return `  <symbol id="${id}" viewBox="0 0 24 24" ${paint}>${inner}</symbol>`
})

const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">
<!-- generated by src/build-icon-sprite.mjs from @tabler/icons (MIT) — do not edit by hand -->
${symbols.join('\n')}
</svg>
`
writeFileSync(join(srcDir, 'assets', 'icons.svg'), sprite)

// the same legacy-name map for the browser side (BazarMap markers, the icon input,
// reaction images... render stored `fa fa-x` choices through the sprite)
const jsMap = Object.fromEntries(
  Object.entries(map).filter(([key]) => key !== '__comment')
)
writeFileSync(
  join(srcDir, '..', 'javascripts', 'yw-icon-map.js'),
  '// generated by src/build-icon-sprite.mjs from src/icon-map.json — do not edit by hand\n'
    + `export const legacyIconMap = ${
      JSON.stringify(jsMap, null, 2)
    }\n`
    + '// every id present in the sprite (the map values + the generator EXTRAS)\n'
    + `const spriteNames = new Set(${
      JSON.stringify(
        names
          .map((ref) => (ref.includes(':') ? `${ref.split(':')[1]}-${ref.split(':')[0]}` : ref))
          .map((id) => id.replace(/-outline$/, ''))
      )
    })\n`
    + 'export function legacyIconToSprite(classString, extraClass = \'\') {\n'
    + '  const symbol = String(classString || \'\').split(/\\s+/).map((c) => c.replace(/^fa-/, \'\')).map((c) => legacyIconMap[c] || (spriteNames.has(c) ? c : null)).find(Boolean)\n'
    + '  if (!symbol) {\n    return null\n  }\n'
    + '  const cls = (\'yw-icon \' + extraClass).trim()\n'
    + '  // base-absolute so the ref survives path-shaped page URLs (/PageTag/edit)\n'
    + '  const base = (typeof wiki !== \'undefined\' && wiki.baseUrl) ? wiki.baseUrl.replace(/\\?+$/, \'\') : \'\'\n'
    + '  return `<svg class="${cls}" aria-hidden="true"><use href="${base}src/assets/icons.svg#${symbol}"/></svg>`\n'
    + '}\n'
)
console.log(
  `icons.svg: ${names.length} symbols, ${(sprite.length / 1024).toFixed(1)} KiB (+ yw-icon-map.js)`
)
